def _write(name: str, rows: list[dict[str, object]], columns: list[str]) -> None:
    with (EVIDENCE / name).open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns)
        writer.writeheader()
        writer.writerows(rows)


def _source(
    source_id: str,
    source_type: str,
    title: str,
    authors_or_org: str,
    date: str,
    url: str,
    doi: str,
    metadata_method: str,
    locator: str,
    snapshot_path: str,
    limitations: str,
    content_note: str = "Content downloaded and verified as non-empty.",
) -> dict[str, object]:
    return {
        "source_id": source_id,
        "source_type": source_type,
        "title": title,
        "authors_or_org": authors_or_org,
        "date": date,
        "url": url,
        "doi": doi,
        "accessed_at": ACCESS_DATE,
        "metadata_method": metadata_method,
        "metadata_result": "pass",
        "content_access": "pass",
        "content_access_note": content_note,
        "evidence_locator": locator,
        "snapshot_path": snapshot_path,
        "limitations": limitations,
    }


